import 'dart:typed_data';

import '../../core/geometry/box.dart';

/// One word on a page: a range of characters and where it sits.
class Word {
  const Word({
    required this.start,
    required this.end,
    required this.box,
    required this.line,
  });

  /// Character range `[start, end)` in the page's character order.
  final int start, end;

  /// Union of the visible characters' boxes, in page space.
  final Box box;

  /// Index into [PageText.lines].
  final int line;

  @override
  String toString() => 'Word($start..$end, $box, line $line)';
}

/// A visual line: consecutive words that share a baseline.
class TextLine {
  const TextLine({
    required this.firstWord,
    required this.endWord,
    required this.box,
  });

  /// Words `[firstWord, endWord)` in [PageText.words].
  final int firstWord, endWord;
  final Box box;

  int get wordCount => endWord - firstWord;
}

/// The text of one page, as characters with boxes, grouped into words and
/// lines (SPEC §6.2).
///
/// Characters are Unicode code points in the order pdfium reports them
/// (content-stream order). The index of a character here is the index used by
/// a highlight's `startChar` / `endChar`. Boxes are in page space (points,
/// origin top-left, y down).
///
/// Only [codes] and [boxes] are stored on disk; words and lines are derived
/// from them in a few milliseconds, so the grouping rules can improve without
/// invalidating the cache.
class PageText {
  PageText._(this.codes, this.boxes, this.words, this.lines, this._charWord);

  /// Builds words and lines from raw characters. [boxes] holds four floats per
  /// character: x0, y0, x1, y1. A character with a zero-size box is invisible
  /// (generated by pdfium): it never starts or ends a word.
  factory PageText.build(Int32List codes, Float32List boxes) {
    if (boxes.length != codes.length * 4) {
      throw ArgumentError('boxes must have 4 floats per character');
    }
    return _Builder(codes, boxes).build();
  }

  static final PageText empty = PageText.build(Int32List(0), Float32List(0));

  final Int32List codes;
  final Float32List boxes;
  final List<Word> words;
  final List<TextLine> lines;
  final Int32List _charWord;

  int get length => codes.length;

  /// False for a scanned page or a figure: there is nothing to select, and
  /// the Mark tool falls back to a free rectangle.
  bool get hasText => words.isNotEmpty;

  Box boxAt(int i) =>
      Box(boxes[i * 4], boxes[i * 4 + 1], boxes[i * 4 + 2], boxes[i * 4 + 3]);

  bool isVisible(int i) => _hasBox(boxes, i);

  /// The word containing character [i], or -1 (whitespace, invisible, out of
  /// range).
  int wordAtChar(int i) => i < 0 || i >= length ? -1 : _charWord[i];

  /// Index of the first word whose end is after character [i] (so it contains
  /// [i] or comes later), or [words].length.
  int firstWordEndingAfter(int i) {
    var lo = 0, hi = words.length;
    while (lo < hi) {
      final mid = (lo + hi) >> 1;
      if (words[mid].end > i) {
        hi = mid;
      } else {
        lo = mid + 1;
      }
    }
    return lo;
  }

  /// The quoted text for characters `[start, end)`, normalized: whitespace
  /// collapsed to single spaces, line-end hyphens removed when a word is
  /// split across lines, ligatures expanded. Characters outside any word
  /// (spaces, generated characters) contribute only the separator.
  String quote(int start, int end) {
    final s = start < 0 ? 0 : start;
    final e = end > length ? length : end;
    if (s >= e) return '';
    final out = StringBuffer();
    var prev = -1;
    String prevText = '';
    for (var w = firstWordEndingAfter(s); w < words.length; w++) {
      final word = words[w];
      if (word.start >= e) break;
      final a = word.start > s ? word.start : s;
      final b = word.end < e ? word.end : e;
      final text = _wordText(a, b);
      if (text.isEmpty) continue;
      if (prev >= 0) {
        final p = words[prev];
        if (p.line == word.line) {
          out.write(' ');
        } else if (_continuesWord(p, prevText, word, text)) {
          // "inter-" / "national": drop a hard hyphen, join with no space.
          if (_endsWithHyphen(prevText)) {
            final all = out.toString();
            out
              ..clear()
              ..write(all.substring(0, all.length - 1));
          }
        } else {
          out.write(' ');
        }
      }
      out.write(text);
      prev = w;
      prevText = text;
    }
    return out.toString();
  }

  /// Up to [n] characters of normalized text just before [start].
  String contextBefore(int start, {int n = 24}) {
    final s = start < 0 ? 0 : start;
    final from = s - n * 2 < 0 ? 0 : s - n * 2;
    final t = quote(from, s);
    return t.length <= n ? t : t.substring(t.length - n);
  }

  /// Up to [n] characters of normalized text just after [end].
  String contextAfter(int end, {int n = 24}) {
    final e = end > length ? length : end;
    final to = e + n * 2 > length ? length : e + n * 2;
    final t = quote(e, to);
    return t.length <= n ? t : t.substring(0, n);
  }

  String _wordText(int a, int b) {
    final sb = StringBuffer();
    for (var i = a; i < b; i++) {
      final c = codes[i];
      if (_isSpace(c)) continue; // interior generated characters
      final lig = _ligatures[c];
      if (lig != null) {
        sb.write(lig);
      } else {
        sb.writeCharCode(c);
      }
    }
    return sb.toString();
  }

  /// A word that was broken by the end of a line: the earlier part ends in a
  /// hyphen (hard, or pdfium's generated soft hyphen between the two words)
  /// and the next part starts in lower case.
  bool _continuesWord(Word p, String prevText, Word w, String text) {
    if (!_startsLower(text)) return false;
    if (_endsWithHyphen(prevText)) {
      return prevText.length > 1 &&
          _isLetter(prevText.codeUnitAt(prevText.length - 2));
    }
    for (var i = p.end; i < w.start; i++) {
      if (_isSoftHyphen(codes[i])) return true;
    }
    return false;
  }
}

// ── character classes ────────────────────────────────────────────────────

const _ligatures = <int, String>{
  0xFB00: 'ff',
  0xFB01: 'fi',
  0xFB02: 'fl',
  0xFB03: 'ffi',
  0xFB04: 'ffl',
  0xFB05: 'st',
  0xFB06: 'st',
};

/// Whitespace, control characters, and the invisible marks pdfium generates
/// (soft hyphen, U+FFFE): all of them separate words.
bool _isSpace(int c) =>
    c <= 0x20 ||
    c == 0x7F ||
    c == 0xA0 ||
    c == 0xAD ||
    (c >= 0x2000 && c <= 0x200F) ||
    c == 0x2028 ||
    c == 0x2029 ||
    c == 0x202F ||
    c == 0x3000 ||
    c == 0xFEFF ||
    c == 0xFFFE ||
    c == 0xFFFF;

/// pdfium writes U+0002 where a line ended in a hyphen it generated.
bool _isSoftHyphen(int c) => c == 0x02 || c == 0xAD;

bool _endsWithHyphen(String s) {
  if (s.isEmpty) return false;
  final c = s.codeUnitAt(s.length - 1);
  return c == 0x2D || c == 0x2010 || c == 0x2011;
}

bool _isLetter(int c) {
  final s = String.fromCharCode(c);
  return s.toLowerCase() != s.toUpperCase();
}

bool _startsLower(String s) {
  if (s.isEmpty) return false;
  final first = String.fromCharCode(s.runes.first);
  return first.toLowerCase() == first && first.toUpperCase() != first;
}

bool _hasBox(Float32List b, int i) {
  final o = i * 4;
  return b[o + 2] > b[o] && b[o + 3] > b[o + 1];
}

// ── building words and lines ─────────────────────────────────────────────

class _Builder {
  _Builder(this.codes, this.b);
  final Int32List codes;
  final Float32List b;

  final words = <_W>[];

  PageText build() {
    final n = codes.length;
    int? start;
    var lastVisible = -1;
    var x0 = 0.0, y0 = 0.0, x1 = 0.0, y1 = 0.0;
    var prevVisible = -1;

    void flush() {
      if (start != null && lastVisible >= start!) {
        words.add(_W(start!, lastVisible + 1, Box(x0, y0, x1, y1)));
      }
      start = null;
      prevVisible = -1;
    }

    for (var i = 0; i < n; i++) {
      if (_isSpace(codes[i])) {
        flush();
        continue;
      }
      if (!_hasBox(b, i)) {
        // Invisible but not whitespace: part of a word only if one is open.
        continue;
      }
      if (start != null && prevVisible >= 0 && _splitsWord(prevVisible, i)) {
        flush();
      }
      final o = i * 4;
      if (start == null) {
        start = i;
        x0 = b[o];
        y0 = b[o + 1];
        x1 = b[o + 2];
        y1 = b[o + 3];
      } else {
        if (b[o] < x0) x0 = b[o];
        if (b[o + 1] < y0) y0 = b[o + 1];
        if (b[o + 2] > x1) x1 = b[o + 2];
        if (b[o + 3] > y1) y1 = b[o + 3];
      }
      lastVisible = i;
      prevVisible = i;
    }
    flush();

    return _group(n);
  }

  /// A word also ends where characters are not adjacent: a gap wider than a
  /// third of the taller glyph (text with no space characters), a jump back
  /// past the previous glyph (a new line), or no vertical overlap at all.
  /// The taller glyph sets the scale because punctuation boxes are tiny: a
  /// comma 2 pt high still sits against the word it follows. Right-to-left
  /// runs have small backward steps and are not split.
  bool _splitsWord(int a, int c) {
    final ao = a * 4, co = c * 4;
    final ah = b[ao + 3] - b[ao + 1];
    final ch = b[co + 3] - b[co + 1];
    final h = ah > ch ? ah : ch;
    final gap = b[co] - b[ao + 2];
    if (gap > 0.35 * h) return true;
    if (gap < -2 * h) return true;
    return _overlap(b[ao + 1], b[ao + 3], b[co + 1], b[co + 3]) <= 0;
  }

  /// Groups words into lines, in content order.
  ///
  /// A line keeps a *band*: the vertical extent of its normal-sized words. A
  /// word joins the line if its centre is within a quarter of a band height
  /// of the band, so punctuation, sub/superscripts and tall glyphs (integral
  /// signs) stay on their line, while the next text line (a full leading
  /// away) does not. Words much taller than the band join but do not widen
  /// it, so one large symbol cannot swallow the line below. A word that
  /// starts more than a band height to the left of the line's right edge is a
  /// new line.
  PageText _group(int n) {
    final charWord = Int32List(n)..fillRange(0, n, -1);
    final out = <Word>[];
    final lines = <TextLine>[];

    var lineFirst = 0;
    var by0 = 0.0, by1 = 0.0; // the band
    Box? lineBox;
    var lineRight = 0.0;

    void closeLine(int endWord) {
      if (lineBox != null) {
        lines.add(
          TextLine(firstWord: lineFirst, endWord: endWord, box: lineBox),
        );
      }
    }

    for (var i = 0; i < words.length; i++) {
      final w = words[i];
      var fits = false;
      if (lineBox != null) {
        final bh = by1 - by0;
        final centre = (w.box.y0 + w.box.y1) / 2;
        fits =
            centre >= by0 - 0.25 * bh &&
            centre <= by1 + 0.25 * bh &&
            w.box.x0 >= lineRight - bh;
      }
      if (fits) {
        lineBox = lineBox!.union(w.box);
        if (w.box.x1 > lineRight) lineRight = w.box.x1;
        if (w.box.height <= 1.5 * (by1 - by0)) {
          if (w.box.y0 < by0) by0 = w.box.y0;
          if (w.box.y1 > by1) by1 = w.box.y1;
        }
      } else {
        closeLine(i);
        lineFirst = i;
        lineBox = w.box;
        by0 = w.box.y0;
        by1 = w.box.y1;
        lineRight = w.box.x1;
      }
      out.add(Word(start: w.start, end: w.end, box: w.box, line: lines.length));
      for (var k = w.start; k < w.end; k++) {
        charWord[k] = i;
      }
    }
    closeLine(words.length);

    return PageText._(codes, b, out, lines, charWord);
  }
}

class _W {
  _W(this.start, this.end, this.box);
  final int start, end;
  final Box box;
}

double _overlap(double a0, double a1, double b0, double b1) {
  final lo = a0 > b0 ? a0 : b0;
  final hi = a1 < b1 ? a1 : b1;
  return hi - lo;
}
